const ATTR_FORMATS = [
	{ id: 'html-title', label: 'HTML with title' },
	{ id: 'html-view', label: 'HTML with view original' },
	{ id: 'html-paren', label: 'HTML parenthetical' },
	{ id: 'html-source', label: 'HTML source format' },
	{ id: 'markdown', label: 'Markdown' },
	{ id: 'plain', label: 'Plain text' },
] as const;

type AttrFormatId = (typeof ATTR_FORMATS)[number]['id'];

function escapeHtml(value: string) {
	return value
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;');
}

function attributionSnippet(format: AttrFormatId, title: string, url: string) {
	const safeTitle = escapeHtml(title);
	switch (format) {
		case 'html-title':
			return `<a href="${url}">${safeTitle}</a>`;
		case 'html-view':
			return `${safeTitle} — <a href="${url}">view original</a>`;
		case 'html-paren':
			return `(<a href="${url}">${safeTitle}</a>)`;
		case 'html-source':
			return `Source: <a href="${url}">${SITE_BRAND}</a>`;
		case 'markdown':
			return `[${title}](${url})`;
		case 'plain':
			return `${title} — Generated by ${SITE_BRAND} ${url}`;
	}
}

